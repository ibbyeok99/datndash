def normalize(s):
    return s.strip()


def load_prior_art():
    mapping = {}
    with open(PRIOR_ART, encoding="utf-8-sig", newline="") as f:
        r = csv.DictReader(f)
        for row in r:
            code = row["기관코드"].strip()
            mapping[code] = {
                "name": row["기관명"].strip(),
                "final": row["국방여부_최종"].strip(),
            }
    return mapping


def main():
    with open(STAGE1, encoding="utf-8-sig", newline="") as f:
        rows = list(csv.DictReader(f))

    prior_art = load_prior_art()

    counts = {
        "tier0": 0, "tierC_contractor": 0, "tierB_mnd_agency": 0, "tier1": 0, "tier2": 0,
        "tier3_resolved": 0, "tier3_new_pending": 0, "tier4_auto_n": 0,
    }
    tier3_new_candidates = []
    out_rows = []

    def emit(code, raw, name, roles, parent, group, is_defense, first_observed_date, review, reason):
        out_rows.append(dict(
            institution_code=code, institution_name_raw=raw,
            institution_name_std=name, institution_roles=roles,
            parent_institution=parent, defense_group=group, is_defense=is_defense,
            first_observed_date=first_observed_date, review_status=review,
            classification_reason=reason,
        ))

    for row in rows:
        code = row["institution_code"]
        name = normalize(row["institution_name_std"])
        raw = row["institution_name_raw"]
        roles = row.get("institution_roles", "")
        first_observed_date = row["first_observed_date"]

        # Tier 0: 기존 검토완료 참조자료 코드 일치
        if code in prior_art and prior_art[code]["final"] in ("Y", "N"):
            final = prior_art[code]["final"]
            group = infer_defense_group(name) if final == "Y" else ""
            parent = infer_parent(name) if final == "Y" else ""
            counts["tier0"] += 1
            reason = f"기존 검토완료 참조자료(국방기관_화이트리스트_검토용_계약정보.csv) 기관코드 일치, 최종판정={final}"
            emit(code, raw, name, roles, parent, group, final, first_observed_date, "자동분류", reason)
            continue

        # Tier C: (비활성화됨 - 방산업체는 N으로 처리하기로 확정)
        if DEFENSE_CONTRACTOR_RE.search(name):
            counts["tierC_contractor"] += 1
            emit(code, raw, name, roles, "", "", "Y", first_observed_date, "자동분류", "(미사용 티어)")
            continue

        # Tier B: 이름에 국방 키워드가 전혀 없어 다른 티어로는 못 잡는, 개별
        # 확인으로 확정한 코드(병무청 계열 + ZD0 코드 개별 확인 사례)
        if code in KNOWN_MND_AGENCY_CODES:
            counts["tierB_mnd_agency"] += 1
            if code.startswith("1300"):
                reason = "정부조직법 제36조: 국방부장관 소속 외청(병무청)으로 확인 - 이름에 국방 키워드 없어 별도 코드 목록으로 확정"
            else:
                reason = "군부대 전용 코드(ZD0#####)이나 이름에 가드 키워드가 전혀 없어 개별 확인 완료 - 90정보통신단(육군 통신부대 유형으로 확인)"
            emit(code, raw, name, roles, "", "국방부", "Y", first_observed_date, "자동분류", reason)
            continue

        # Tier 1: 최상위 유일 기관 (정확한 이름 일치)
        if name in TOP_LEVEL:
            counts["tier1"] += 1
            reason = f"최상위 국방기관명 '{name}'과 정확히 일치"
            emit(code, raw, name, roles, "", TOP_LEVEL[name], "Y", first_observed_date, "자동분류", reason)
            continue

        # Tier 2: ZD0##### 코드 + 부대성 명사
        if ZD_CODE_RE.match(code) and UNIT_NOUN_RE.search(name) and not EXCLUDE_RE.search(name):
            counts["tier2"] += 1
            matched_noun = UNIT_NOUN_RE.search(name).group()
            reason = f"기관코드가 군부대 전용 코드 패턴(ZD0#####)이며 기관명에 부대성 표현('{matched_noun}') 포함"
            emit(code, raw, name, roles, infer_parent(name), infer_defense_group(name),
                 "Y", first_observed_date, "자동분류", reason)
            continue

        # Tier 3: 가드 키워드 후보 -> 개별 검토 결과 반영
        guard_hit = None
        if not EXCLUDE_RE.search(name):
            for kw, pat in GUARDS:
                if pat.search(name):
                    guard_hit = kw
                    break

        if guard_hit:
            if code in TIER3_RESOLUTIONS:
                is_def, group, parent, note = TIER3_RESOLUTIONS[code]
                review = "자동분류" if is_def else "수동확인"
                counts["tier3_resolved"] += 1
                reason = f"국방 관련 키워드('{guard_hit}') 포함, 코드로는 뒷받침 안 되어 개별 확인 완료 - {note}"
                emit(code, raw, name, roles, parent, group, is_def, first_observed_date, review, reason)
            else:
                # 데이터가 바뀌어 새로 등장한 후보 -> 추측하지 않고 수동확인
                counts["tier3_new_pending"] += 1
                tier3_new_candidates.append({"code": code, "name": name, "raw": raw, "matched_keyword": guard_hit})
                reason = f"국방 관련 키워드('{guard_hit}') 포함되나 코드로 뒷받침 안 되고 아직 개별 확인 전 - 확인 필요"
                emit(code, raw, name, roles, "", "", "", first_observed_date, "수동확인", reason)
            continue

        # Tier 4: 국방 관련 키워드/방산업체 신호가 전혀 없음 -> N 확정
        counts["tier4_auto_n"] += 1
        reason = "기관명에 국방 관련 키워드(국방/육군/해군/공군/국군/사단/연대/사관/방위사업청/군단/부대 등) 전무"
        emit(code, raw, name, roles, "", "", "N", first_observed_date, "자동분류", reason)

    # Y로 확정된 기관은 문자열 매칭이 아니라 실제 조직 체계 조사 결과
    # (Y_HIERARCHY)로 parent_institution/defense_group을 덮어쓴다.
    hierarchy_applied = 0
    hierarchy_missing = []
    for r in out_rows:
        if r["is_defense"] != "Y":
            continue
        if r["institution_code"] in Y_HIERARCHY:
            parent, group = Y_HIERARCHY[r["institution_code"]]
            r["parent_institution"] = parent
            r["defense_group"] = group
            hierarchy_applied += 1
        else:
            hierarchy_missing.append(r["institution_code"])

    # parent_institution이 defense_group과 값이 같으면(예: 둘 다 "국방부")
    # 정보 중복이므로 parent_institution을 공란으로 정리한다.
    same_value_cleared = 0
    for r in out_rows:
        if r["parent_institution"] and r["parent_institution"] == r["defense_group"]:
            r["parent_institution"] = ""
            same_value_cleared += 1

    print(json.dumps(counts, ensure_ascii=False, indent=2))
    print(f"parent==defense_group 중복 정리(공란 처리): {same_value_cleared}건")
    print(f"Y_HIERARCHY applied: {hierarchy_applied}, missing (still string-matched): {hierarchy_missing}")
    if tier3_new_candidates:
        print(f"NEW unresolved tier3 candidates (need review): {len(tier3_new_candidates)}")
        with open(TIER3_CANDIDATES_OUT, "w", encoding="utf-8") as f:
            json.dump(tier3_new_candidates, f, ensure_ascii=False, indent=2)

    with open(OUT_CSV, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.DictWriter(
            f,
            fieldnames=[
                "institution_code", "institution_name_raw", "institution_name_std",
                "institution_roles", "parent_institution", "defense_group", "is_defense",
                "first_observed_date", "review_status", "classification_reason",
            ],
        )
        w.writeheader()
        w.writerows(out_rows)
    print(f"Wrote {OUT_CSV} ({len(out_rows)} rows)")


if __name__ == "__main__":
    main()
